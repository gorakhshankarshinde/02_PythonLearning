'''
We are going to learn classes and objects in Python programming.

# Class is a blue print of an object.
# Object is an instance of a class.
'''

# Example 1

class Student:
    subject = "Python"
    std = 12
    collegeName = "ABC"

stud = Student() # here stud object of Student class

# If we try to print stud object it will show the memory address of that object location.

print(stud)


print(stud.subject)
print(stud.std)
print(stud.collegeName)







